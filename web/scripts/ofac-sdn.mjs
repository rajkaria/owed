// Builds Owed's sanctions snapshot from the U.S. Treasury's OFAC SDN list.
//
//   cd web && node scripts/ofac-sdn.mjs              # download SDN.XML from Treasury
//   cd web && node scripts/ofac-sdn.mjs <sdn.xml>    # or read a downloaded copy
//
// Keeps every "Digital Currency Address" that Owed can be asked to pay: Solana addresses (base58,
// 32 bytes) and EVM addresses (0x + 40 hex, for Base requests), with the entry's name and programs.
// Writes the same generated module to plugin/src/ofac-sdn.ts and web/lib/ofac-sdn.ts (a web test
// checks they are equal). Nothing else is kept and nothing is edited by hand. Re-run it before a
// release to pick up new designations; the generated file records the list's publish date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import bs58 from "bs58";

const SOURCE = "https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports/SDN.XML";
const WEB = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = [join(WEB, "lib/ofac-sdn.ts"), join(WEB, "../plugin/src/ofac-sdn.ts")];

const xml = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(SOURCE, { signal: AbortSignal.timeout(120_000) })).text();
if (!xml.includes("<sdnList")) throw new Error("not an SDN list");

const text = (block, tag) => block.match(new RegExp(`<${tag}>([^<]*)</${tag}>`))?.[1]?.trim() ?? "";
const decode = (s) => s.replace(/&amp;/g, "&").replace(/&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">");

function isSolana(s) {
  if (!/^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(s)) return false;
  try {
    return bs58.decode(s).length === 32;
  } catch {
    return false;
  }
}
const isEvm = (s) => /^0x[0-9a-fA-F]{40}$/.test(s);

const published = text(xml, "Publish_Date"); // MM/DD/YYYY
const [mm, dd, yyyy] = published.split("/");
const entries = [];
for (const [, block] of xml.matchAll(/<sdnEntry>([\s\S]*?)<\/sdnEntry>/g)) {
  const first = decode(text(block, "firstName"));
  const last = decode(text(block, "lastName"));
  const name = [first, last].filter(Boolean).join(" ");
  const programs = [...block.matchAll(/<program>([^<]+)<\/program>/g)].map((m) => m[1].trim());
  for (const [, id] of block.matchAll(/<id>([\s\S]*?)<\/id>/g)) {
    const type = text(id, "idType");
    if (!type.startsWith("Digital Currency Address - ")) continue;
    const address = text(id, "idNumber");
    const kind = isSolana(address) ? "solana" : isEvm(address) ? "evm" : null;
    if (!kind) continue;
    entries.push({ address: kind === "evm" ? address.toLowerCase() : address, kind, currency: type.slice("Digital Currency Address - ".length), name, programs, uid: text(block, "uid") });
  }
}
const seen = new Set();
const unique = entries
  .sort((a, b) => (a.kind === b.kind ? (a.address < b.address ? -1 : a.address > b.address ? 1 : 0) : a.kind === "solana" ? -1 : 1))
  .filter((e) => (seen.has(e.address) ? false : (seen.add(e.address), true)));

const body = `// Generated by web/scripts/ofac-sdn.mjs from the U.S. Treasury's OFAC SDN list. Do not edit by hand.
// Solana and EVM digital currency addresses only (what Owed can be asked to pay). The same file is at
// plugin/src/ofac-sdn.ts and web/lib/ofac-sdn.ts.

export interface SdnAddress {
  /** Base58 for Solana; lower-case 0x hex for EVM. */
  address: string;
  kind: "solana" | "evm";
  /** As OFAC labels it: "Digital Currency Address - <currency>". */
  currency: string;
  name: string;
  programs: string[];
  uid: string;
}

export const OFAC_SDN: { source: string; published: string; addresses: SdnAddress[] } = {
  source: ${JSON.stringify(SOURCE)},
  published: ${JSON.stringify(`${yyyy}-${mm}-${dd}`)},
  addresses: ${JSON.stringify(unique, null, 2).replace(/\n/g, "\n  ")},
};
`;
for (const path of OUT) writeFileSync(path, body);
const count = (k) => unique.filter((e) => e.kind === k).length;
console.log(`SDN list published ${yyyy}-${mm}-${dd}: ${count("solana")} Solana and ${count("evm")} EVM addresses → ${OUT.join(", ")}`);
